#!/usr/bin/env python3
"""
build_gen.py -- 把 index.html 转成 C 头文件 index_html.h
用法: python build_gen.py index.html index_html.h
"""
import sys

def main():
    if len(sys.argv) != 3:
        print("用法: python build_gen.py <input.html> <output.h>")
        sys.exit(1)

    src, dst = sys.argv[1], sys.argv[2]

    with open(src, "rb") as f:
        data = f.read()

    with open(dst, "w", encoding="utf-8") as out:
        out.write("/* Auto-generated by build_gen.py — do not edit. */\n")
        out.write(f"static const unsigned char index_html[{len(data)}] = {{\n")
        for i in range(0, len(data), 16):
            chunk = data[i:i+16]
            out.write("    " + ",".join(f"0x{b:02x}" for b in chunk) + ",\n")
        out.write("};\n")
        out.write(f"static const unsigned int index_html_len = {len(data)};\n")

    print(f"Generated {dst} ({len(data)} bytes)")

if __name__ == "__main__":
    main()
